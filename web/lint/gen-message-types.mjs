// next-intl types the arguments of a message from a `.d.json.ts` beside each JSON file: a plain `{n}`
// then takes only a string, so a number passed to it fails `tsc`. `pnpm typecheck` and `pnpm build`
// run this first, because tsc reads a stale copy in place of the JSON.
import { readdirSync, writeFileSync } from 'node:fs';
import { readFile } from 'node:fs/promises';
import path from 'node:path';

const dir = path.join(import.meta.dirname, '..', 'messages');
const files = readdirSync(dir).filter((f) => f.endsWith('.json'));

await Promise.all(
  files.map(async (file) => {
    const content = await readFile(path.join(dir, file), 'utf-8');
    writeFileSync(
      path.join(dir, file.replace(/\.json$/, '.d.json.ts')),
      `// biome-ignore-all format: generated by lint/gen-message-types.mjs\ndeclare const messages: ${content.trim()};\nexport default messages;\n`,
    );
  }),
);
