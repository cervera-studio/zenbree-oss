"""Pure inbound rules (#86, #75): Svix signature, own words, opt-out and autoresponder detection."""

import base64
import hashlib
import hmac
import itertools

import pytest

from app.outreach.inbound import (
    ReplyClass,
    is_auto_reply,
    is_opt_out,
    message_ids,
    safer,
    sender_authenticated,
    strip_quoted_reply,
    verify_svix,
    vote,
)

KEY = b'0123456789abcdef0123456789abcdef'
SECRET = 'whsec_' + base64.b64encode(KEY).decode()


def sign(msg_id: str, ts: str, body: bytes, key: bytes = KEY) -> str:
    digest = hmac.new(key, f'{msg_id}.{ts}.'.encode() + body, hashlib.sha256).digest()
    return 'v1,' + base64.b64encode(digest).decode()


def test_svix_signature():
    body = b'{"type":"email.received"}'
    good = sign('msg_1', '1000', body)
    assert verify_svix(secret=SECRET, msg_id='msg_1', timestamp='1000', signature=good, body=body, now=1000)
    assert verify_svix(secret=SECRET, msg_id='msg_1', timestamp='1000', signature=f'v1,old {good}', body=body, now=1000)
    assert not verify_svix(secret=SECRET, msg_id='msg_1', timestamp='1000', signature=good, body=body + b' ', now=1000)
    assert not verify_svix(secret=SECRET, msg_id='msg_2', timestamp='1000', signature=good, body=body, now=1000)
    assert not verify_svix(secret=SECRET, msg_id='msg_1', timestamp='1000', signature=good, body=body, now=2000)
    assert not verify_svix(secret='', msg_id='msg_1', timestamp='1000', signature=good, body=body, now=1000)


def test_own_words_drop_the_quoted_original():
    text = 'Sì, sentiamoci giovedì\n\nIl giorno lun 5 ott 2026, Marco ha scritto:\n> Ciao Anna\n> no grazie'
    assert strip_quoted_reply(text) == 'Sì, sentiamoci giovedì'
    assert strip_quoted_reply('> only quoted\n> text') == ''


def test_opt_out_is_explicit_and_in_their_own_words():
    assert is_opt_out(subject='Re: Ciao', text='No grazie')
    assert is_opt_out(subject='Re: Ciao', text='Ciao Marco, no, grazie.\n\nOn Mon, Marco wrote:\n> ...')
    assert is_opt_out(subject='Re: x', text='Please remove me from your list')
    assert is_opt_out(subject='unsubscribe', text='')  # the List-Unsubscribe mailto
    # Our own footer quoted back under a positive answer is not their opt-out.
    footer = 'Per non ricevere altri messaggi, è sufficiente rispondere "no grazie"'
    assert not is_opt_out(subject='Re: Ciao', text=f'Volentieri!\n\nOn Mon, Marco wrote:\n> {footer}')
    assert not is_opt_out(subject='Re: Ciao', text='Grazie, ne parliamo la prossima settimana')
    # Declines now, not forever: a reply the LLM labels not_now, never a permanent exclusion.
    assert not is_opt_out(subject='Re: Ciao', text='No, grazie per la mail, sentiamoci a gennaio')
    assert is_opt_out(subject='Re: Ciao', text='Please unsubscribe me')
    assert is_opt_out(subject='Re: Ciao', text='please stop emailing me')
    assert is_opt_out(subject='Re: Ciao', text='Cancellami')
    assert is_opt_out(subject='unsubscribe', text='This message was automatically generated by Gmail.')


def test_autoresponders():
    assert is_auto_reply(subject='Risposta automatica: Ciao Anna', headers={})
    assert is_auto_reply(subject='Re: Ciao', headers={'auto-submitted': 'auto-replied'})
    assert not is_auto_reply(subject='Re: Out of office tools', headers={})


def test_message_ids():
    assert message_ids('<a@x>', '<r@x> <a@x>') == ['<a@x>', '<r@x>', '<a@x>']


@pytest.mark.parametrize(
    ('authentication', 'expected'),
    [
        ({'spf': 'pass', 'dkim': 'pass', 'dmarc': 'pass'}, True),
        ({'dmarc': 'PASS'}, True),
        ({'dmarc': 'fail'}, False),
        ({'dmarc': 'gray'}, None),
        ({'dmarc': 'processing_failed'}, None),
        ({'dmarc': 'unknown'}, None),
        ({'dmarc': 'none'}, None),
        ({'spf': 'pass', 'dkim': 'pass'}, None),
        ({'dmarc': ''}, None),
        ({'dmarc': None}, None),
        ({}, None),
        (None, None),
        ('dmarc=pass', None),
        (['dmarc', 'pass'], None),
    ],
)
def test_sender_authenticated_reads_the_receivers_dmarc_verdict(authentication, expected):
    assert sender_authenticated(authentication) is expected


def test_svix_non_ascii_signature_is_refused():
    kwargs = {'secret': SECRET, 'msg_id': 'msg_1', 'timestamp': '1000', 'body': b'{}', 'now': 1000}
    assert not verify_svix(signature='v1,é', **kwargs)


@pytest.mark.parametrize(
    ('subject', 'text', 'headers', 'expected'),
    [
        ('Re: Ciao', 'Volentieri, sentiamoci', None, ReplyClass.HUMAN),
        ('Re: Ciao', 'No grazie', None, ReplyClass.OPT_OUT),
        ('Fuori ufficio', 'No grazie', None, ReplyClass.AUTO),
        ('Re: Ciao', 'No grazie', {'auto-submitted': 'auto-replied'}, ReplyClass.AUTO),
    ],
)
def test_the_vote_reads_an_autoresponder_before_an_opt_out(subject, text, headers, expected):
    assert vote(subject=subject, text=text, headers=headers) == expected


@pytest.mark.parametrize('votes', list(itertools.permutations([ReplyClass.AUTO, ReplyClass.HUMAN, ReplyClass.OPT_OUT])))
def test_the_safer_class_wins_in_any_order(votes):
    assert safer(*votes) == ReplyClass.OPT_OUT
    assert safer(*[v for v in votes if v != ReplyClass.OPT_OUT]) == ReplyClass.HUMAN
    assert safer(ReplyClass.AUTO, None, ReplyClass.AUTO) == ReplyClass.AUTO
    assert safer(None, None) is None
